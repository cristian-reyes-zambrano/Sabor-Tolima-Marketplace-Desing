// ─── Helpers ──────────────────────────────────────────────────────────────────

export function getRestaurantsByCategory(category: Category): Restaurant[] {
  return restaurants.filter((r) => r.categories.includes(category));
}

export function searchRestaurants(query: string): Restaurant[] {
  const q = query.toLowerCase();
  return restaurants.filter(
    (r) =>
      r.name.toLowerCase().includes(q) ||
      r.description.toLowerCase().includes(q) ||
      r.tags.some((t) => t.toLowerCase().includes(q))
  );
}

export function getTopRestaurants(limit = 6): Restaurant[] {
  return [...restaurants].sort((a, b) => b.rating - a.rating).slice(0, limit);
}

export function getRestaurantsWithDiscounts(): Restaurant[] {
  return restaurants.filter((r) => r.discount);
}

export function getRestaurantById(id: string): Restaurant | undefined {
  return restaurants.find((r) => r.id === id);
}
